const express = require("express")
const router = express.Router()
const {getMyQueueStatus}=require("../controllers/queueStatusController")
const {getAdminQueue}=require("../controllers/adminQueueController")
const {joinQueue} = require("../controllers/queueController")
const authMiddleware = require("../middleware/authMiddleware")
const adminMiddleware = require("../middleware/adminMiddleware")
const { callNextCustomer } = require("../controllers/callNextController")
const {updateCustomerStatus}=require("../controllers/customerActionController")
const {cancelQueueEntry}=require("../controllers/cancelQueueController")
const {closeQueueSession}=require("../controllers/closeQueueSessionController")
const {startQueueSession}=require("../controllers/startQueueSessionController")
const { getActiveQueueCount } = require("../controllers/activeQueueCountController")
const {getActiveQueueSessions} = require("../controllers/activeQueueSessionsController")
const { updateQueuePriority } = require("../controllers/priorityController")
router.post("/join",authMiddleware,joinQueue)
router.get("/my-status",authMiddleware,getMyQueueStatus)
router.get("/admin/active-sessions",authMiddleware,adminMiddleware,getActiveQueueSessions)
router.get("/admin/:sessionId",authMiddleware,adminMiddleware,getAdminQueue)
router.post("/admin/:sessionId/next",authMiddleware,adminMiddleware,callNextCustomer)
router.patch("/admin/entries/:entryId/status",authMiddleware,adminMiddleware,updateCustomerStatus)
router.patch("/my-entry/:entryId/cancel",authMiddleware,cancelQueueEntry)
router.patch("/admin/:sessionId/close",authMiddleware,adminMiddleware,closeQueueSession)
router.post("/admin/:serviceId/start",authMiddleware,adminMiddleware,startQueueSession)
router.get("/active-count", getActiveQueueCount)
router.patch("/admin/entries/:entryId/priority",authMiddleware,adminMiddleware,updateQueuePriority)
module.exports=router